-- 0017: sku_catalog case normalisation + latest Apple/Samsung model expansion.
--
-- Part A — normalisation ("UPPER() everywhere"):
--   The original 14 Samsung demo rows (imported before the 2,10x-row bulk
--   sync) were stored as brand="Samsung"/model="Galaxy S24" etc. (mixed
--   case), while every row synced afterwards uses brand="SAMSUNG"/
--   model="GALAXY S24" (upper case). resolveCatalogSku() already matches
--   case-insensitively (UPPER() in every WHERE clause), so this was never a
--   functional bug — but having two textually different casings of the same
--   brand/model in one table is confusing on the Catalog tab UI and, worse,
--   two of the legacy names ("Galaxy S22 Plus" / "Galaxy S23 Plus") didn't
--   even match the "+" suffix convention the newer rows use, so they were
--   TEXTUALLY duplicate models under different names. This migration:
--     1. Upper-cases brand, model, color on every row.
--     2. Renames the two "... PLUS" legacy models to the canonical "...+"
--        form used everywhere else, which makes them collide (exact same
--        model/capacity/color) with 5 existing canonical SAM-* rows —
--        those 5 legacy duplicates (SMSG-S22P-256-BLK, SMSG-S23-256-BLK,
--        SMSG-S23-512-BLK, SMSG-S23P-256-BLK, SMSG-S23P-512-BLK) are
--        deleted in favour of the newer SAM-* SKU that already covers the
--        exact same model+capacity+color+grade. Verified before deleting:
--        neither received_devices nor expected_devices reference any of
--        these 5 legacy SKUs.
--     3. Normalises the legacy rows' capacity ("256G" -> "256GB", matching
--        migration 0007's canonical form) and backfills their NULL grade
--        column to 'UG' (these rows predate the grade column entirely).
--
-- Part B — catalogue expansion ("latest models and their variations"):
--   Adds the current-generation Apple and Samsung lines that were missing,
--   plus a couple of older gaps seen in real manifest data (iPhone XR,
--   iPhone SE, Galaxy Z Fold6/Flip6, Galaxy S25 FE) — each combination
--   gets all 4 grades (A/B/C/UG), following the existing
--   {PREFIX}-{CAPACITY}-{COLOR-CODE}-{GRADE} SKU convention:
--     APPLE:   iPhone 17, iPhone 17 Pro, iPhone 17 Pro Max, iPhone Air,
--              iPhone XR, iPhone SE (3rd gen)
--     SAMSUNG: Galaxy S26, S26+, S26 Ultra, Galaxy S25 FE,
--              Galaxy Z Fold6, Z Flip6, Z Fold7, Z Flip7
--   668 new rows total. INSERT OR IGNORE keeps this idempotent/safe to
--   re-run (sku is UNIQUE).

-- ── Part A: normalise casing ────────────────────────────────────────────
UPDATE sku_catalog SET brand = UPPER(brand) WHERE brand IS NOT NULL AND brand != UPPER(brand);
UPDATE sku_catalog SET model = UPPER(model) WHERE model IS NOT NULL AND model != UPPER(model);
UPDATE sku_catalog SET color = UPPER(color) WHERE color IS NOT NULL AND color != UPPER(color);

UPDATE sku_catalog SET model = 'GALAXY S22+' WHERE model = 'GALAXY S22 PLUS';
UPDATE sku_catalog SET model = 'GALAXY S23+' WHERE model = 'GALAXY S23 PLUS';

DELETE FROM sku_catalog WHERE sku IN (
  'SMSG-S22P-256-BLK',
  'SMSG-S23-256-BLK',
  'SMSG-S23-512-BLK',
  'SMSG-S23P-256-BLK',
  'SMSG-S23P-512-BLK'
);

UPDATE sku_catalog
SET capacity = CASE
  WHEN capacity IS NULL OR capacity = '' THEN capacity
  WHEN capacity GLOB '*[0-9]GB' THEN capacity
  WHEN capacity GLOB '*[0-9]G'  THEN capacity || 'B'
  WHEN capacity GLOB '[0-9]*' AND NOT capacity GLOB '*[A-Za-z]*' THEN capacity || 'GB'
  ELSE capacity
END
WHERE capacity IS NOT NULL;

UPDATE sku_catalog SET grade = 'UG' WHERE grade IS NULL;

